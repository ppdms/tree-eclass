import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir, mkdtemp, rename, rm, realpath, lstat } from 'node:fs/promises';
import { basename, dirname, join, resolve, relative, sep, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createTransforms } from './transform.mjs';
import { removeMeasureStyle } from './measure-abi.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const surface = JSON.parse(await readFile(join(root, 'surface.json'), 'utf8'));
const toolHashes = JSON.parse(await readFile(join(root, 'tool-hashes.json'), 'utf8'));
const expectedProducts = JSON.parse(await readFile(join(root, 'expected-products.json'), 'utf8'));
const require = createRequire(import.meta.url);
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const banner =
  '// Derived from taffy-layout 3.0.0; Copyright (c) 2026 ByteLand Technology Limited.\n' +
  '// MIT license: see the accompanying LICENSE. Generated by taffy-trim/2.\n';

function argumentsFromCLI(argv) {
  const result = {};
  const allowed = new Set(['--input', '--output', '--typescript', '--binaryen']);
  for (let i = 0; i < argv.length; i += 2) {
    if (!allowed.has(argv[i]) || !argv[i + 1] || argv[i + 1].startsWith('--')) {
      throw new Error('Expected --input DIR --output NEW_DIR --typescript DIR --binaryen DIR');
    }
    if (Object.hasOwn(result, argv[i])) throw new Error(`Repeated argument ${argv[i]}`);
    result[argv[i]] = resolve(argv[i + 1]);
  }
  for (const name of allowed) if (!result[name]) throw new Error(`Required: ${name}`);
  return result;
}

function nested(parent, child) {
  const path = relative(parent, child);
  return path === '' || (!isAbsolute(path) && path !== '..' && !path.startsWith(`..${sep}`));
}

async function pinnedFile(directory, path) {
  const target = await realpath(join(directory, path));
  if (!nested(directory, target)) throw new Error(`Pinned input escapes its directory: ${path}`);
  return readFile(target);
}

async function pinnedTool(directory, name, version) {
  directory = await realpath(directory);
  const metadata = JSON.parse((await pinnedFile(directory, 'package.json')).toString('utf8'));
  if (metadata.name !== name || metadata.version !== version) throw new Error(`Expected ${name}@${version}`);
  for (const [path, expected] of Object.entries(toolHashes)) {
    if (path.startsWith(`${name}/`)) {
      const bytes = await pinnedFile(directory, path.slice(name.length + 1));
      if (sha256(bytes) !== expected) throw new Error(`Pinned tool changed: ${path}`);
    }
  }
  return directory;
}

async function pinnedInputs(input) {
  const metadata = JSON.parse((await pinnedFile(input, 'package.json')).toString('utf8'));
  if (metadata.name !== surface.package.name || metadata.version !== surface.package.version) {
    throw new Error(`Expected ${surface.package.name}@${surface.package.version}`);
  }
  const inputs = {};
  for (const [path, expected] of Object.entries(surface.inputs)) {
    const bytes = await pinnedFile(input, path);
    if (sha256(bytes) !== expected) throw new Error(`${path}: SHA-256 mismatch; audit upgrades before changing pins`);
    inputs[path] = bytes;
  }
  return inputs;
}

function runBinaryen(binaryen, tool, args) {
  const result = spawnSync(process.execPath, [join(binaryen, 'bin', tool), ...args], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    timeout: 300000,
    env: { ...process.env, BINARYEN_CORES: '1' },
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${tool} failed (${result.status}):\n${result.stderr}\n${result.stdout}`);
  return { stdout: result.stdout, stderr: result.stderr };
}

function requireExports(exports) {
  const expected = new Set(surface.retainedWasmExports);
  const names = new Set(exports.map((item) => item.name));
  for (const name of expected) if (!names.has(name)) throw new Error(`Missing required WASM export ${name}`);
  if (names.size !== expected.size) throw new Error('Binaryen retained an unlisted WASM export');
  for (const item of exports) {
    const kind = item.name === 'memory' ? 'memory' : item.name === '__wbindgen_externrefs' ? 'table' : 'function';
    if (item.kind !== kind) throw new Error(`Unexpected export kind ${item.name}: ${item.kind}`);
  }
}

function sourceGraph(inputs, transforms) {
  const original = new WebAssembly.Module(inputs['pkg/taffy_wasm_bg.wasm']);
  const exports = WebAssembly.Module.exports(original);
  const imports = WebAssembly.Module.imports(original);
  const expected = surface.originalWasmInventory;
  if (exports.length !== expected.exports || imports.length !== expected.imports) {
    throw new Error('Unexpected original module inventory');
  }
  for (const name of surface.retainedWasmExports) {
    if (!exports.some((item) => item.name === name)) throw new Error(`Pinned input does not export ${name}`);
  }
  const text = inputs['pkg/taffy_wasm.js'].toString('utf8');
  return { graph: transforms.prepare(text, exports, imports), imports, text };
}

async function optimize(input, work, binaryen, graph, originalImports) {
  const graphPath = join(work, 'metadce-graph.json');
  const pruned = join(work, 'export-pruned.wasm');
  const optimized = join(work, 'taffy_wasm_bg.wasm');
  await writeFile(graphPath, json(graph));
  const features = surface.binaryenFeatures;
  const meta = runBinaryen(binaryen, 'wasm-metadce', [
    join(input, 'pkg/taffy_wasm_bg.wasm'),
    ...features,
    '-f',
    graphPath,
    '-o',
    pruned,
  ]);
  const opt = runBinaryen(binaryen, 'wasm-opt', [pruned, ...features, ...surface.binaryenPasses, '-o', optimized]);
  const native = await removeMeasureStyle(await readFile(optimized), binaryen);
  const wasm = native.wasm;
  const module = new WebAssembly.Module(wasm); // Inspect ABI only; never instantiate or execute it.
  const exports = WebAssembly.Module.exports(module);
  const imports = WebAssembly.Module.imports(module);
  requireExports(exports);
  const originalKeys = new Set(originalImports.map((item) => `${item.module}:${item.name}:${item.kind}`));
  for (const item of imports) {
    if (!originalKeys.has(`${item.module}:${item.name}:${item.kind}`)) throw new Error('Unexpected new WASM import');
  }
  return { wasm, imports, exports, meta, opt, measureABI: native.proof };
}

async function products(inputs, source, result, transforms) {
  return {
    'taffy_wasm_bg.wasm': result.wasm,
    'taffy_wasm.js': banner + transforms.runtime(source.text, result.imports),
    'taffy_wasm.d.ts': banner + transforms.declarations(inputs['pkg/taffy_wasm.d.ts'].toString('utf8')),
    'taffy_wasm_bg.wasm.d.ts':
      banner + transforms.wasmDeclarations(inputs['pkg/taffy_wasm_bg.wasm.d.ts'].toString('utf8')),
    'index.js': await readFile(join(root, 'adapter/index.js')),
    'index.d.ts': await readFile(join(root, 'adapter/index.d.ts')),
    LICENSE: inputs.LICENSE,
    'package.json': json({
      name: 'tree-canvas-taffy',
      version: '3.0.0-trim.2',
      private: true,
      type: 'module',
      license: 'MIT',
      main: './index.js',
      types: './index.d.ts',
      exports: {
        '.': { types: './index.d.ts', import: './index.js' },
        './wasm': { types: './index.d.ts', import: './index.js' },
      },
    }),
    'metadce-graph.json': json(source.graph),
    'metadce-unused.txt': result.meta.stdout,
    'binaryen-diagnostics.txt': result.meta.stderr + result.opt.stdout + result.opt.stderr,
  };
}

function generationManifest(files, inputs, result) {
  const output = Object.fromEntries(
    Object.entries(files).map(([path, bytes]) => {
      const data = typeof bytes === 'string' ? Buffer.from(bytes) : bytes;
      return [path, { bytes: data.byteLength, sha256: sha256(data) }];
    }),
  );
  return json({
    generator: surface.generator,
    package: surface.package,
    tools: surface.tools,
    inputs: surface.inputs,
    output,
    retainedWasmExports: surface.retainedWasmExports,
    liveWasmImports: result.imports,
    binaryenFeatures: surface.binaryenFeatures,
    binaryenPasses: surface.binaryenPasses,
    measureABI: result.measureABI,
    preservedSourceFeatures: surface.preservedSourceFeatures,
    runtimeClasses: Object.fromEntries(Object.entries(surface.classes).map(([name, value]) => [name, value.runtime])),
    comparisonInputs: {
      wasmBytes: inputs['pkg/taffy_wasm_bg.wasm'].byteLength,
      glueBytes: inputs['pkg/taffy_wasm.js'].byteLength,
    },
    verification: { executedModule: false, browserFixtures: false, appBuild: false },
  });
}

function requireMatchedProducts(files) {
  for (const [path, expected] of Object.entries(expectedProducts)) {
    const bytes = typeof files[path] === 'string' ? Buffer.from(files[path]) : files[path];
    if (!bytes || bytes.byteLength !== expected.bytes || sha256(bytes) !== expected.sha256) {
      throw new Error(`Generated product differs from pinned candidate: ${path}`);
    }
  }
}

async function outputWorkspace(path, roots) {
  const output = join(await realpath(dirname(path)), basename(path));
  for (const root of roots) {
    if (nested(root, output) || nested(output, root)) throw new Error('Input/tool/output directories must be disjoint');
  }
  await mkdir(output); // Exclusive creation rejects existing directories and symlinks without touching them.
  const work = await mkdtemp(join(output, '.work-'));
  return { output, work, identity: await lstat(work) };
}

async function removeWorkspace(workspace) {
  const { work, identity } = workspace;
  const current = await lstat(work);
  if (
    current.isSymbolicLink() ||
    current.dev !== identity.dev ||
    current.ino !== identity.ino ||
    (await realpath(work)) !== work
  )
    throw new Error('Generator workspace identity changed; refusing cleanup');
  await rm(work, { recursive: true });
}

async function main() {
  if (Number(process.versions.node.split('.')[0]) < 22) throw new Error('Node 22 or later is required');
  const args = argumentsFromCLI(process.argv.slice(2));
  const input = await realpath(args['--input']);
  const inputs = await pinnedInputs(input);
  const typescript = await pinnedTool(args['--typescript'], 'typescript', surface.tools.typescript);
  const binaryen = await pinnedTool(args['--binaryen'], 'binaryen', surface.tools.binaryen);
  const ts = require(join(typescript, 'lib/typescript.js'));
  if (ts.version !== surface.tools.typescript) throw new Error('TypeScript implementation version mismatch');
  const transforms = createTransforms(ts, surface);
  const source = sourceGraph(inputs, transforms);
  const workspace = await outputWorkspace(args['--output'], [input, typescript, binaryen]);
  const { output, work } = workspace;
  try {
    const result = await optimize(input, work, binaryen, source.graph, source.imports);
    const files = await products(inputs, source, result, transforms);
    requireMatchedProducts(files);
    files['generation-manifest.json'] = generationManifest(files, inputs, result);
    for (const [path, bytes] of Object.entries(files)) await writeFile(join(work, path), bytes);
    for (const path of Object.keys(files)) await rename(join(work, path), join(output, path));
    console.log(
      json({
        output,
        retainedExportCount: result.exports.length,
        liveImportCount: result.imports.length,
        wasmBytes: result.wasm.byteLength,
        glueBytes: Buffer.byteLength(files['taffy_wasm.js']),
      }),
    );
  } finally {
    await removeWorkspace(workspace);
  }
}

await main();
