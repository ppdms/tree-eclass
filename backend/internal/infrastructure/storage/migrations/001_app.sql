                    'past_paper', 'student_notes', 'study_guide', 'textbook',
                    'exercise_solution', 'lecture_material', 'other'
                )),
                source_label TEXT,
                notes TEXT,
                created_at TEXT DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                updated_at TEXT DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                PRIMARY KEY (course_id, source_path),
                FOREIGN KEY (course_id) REFERENCES app.courses (id) ON DELETE CASCADE
            );

